#!/usr/bin/env bash
# install.sh — automated, user-level installer for Transcriptomics Preprocessor.
#
# What it does (no root, no sudo, no edits to shell start-up files):
#   1. checks the operating system, CPU architecture, basic utilities and free space;
#   2. finds or downloads a pinned micromamba (SHA-256 verified before it is executed);
#   3. creates an isolated conda environment from the checksummed lock file
#      (SRA Toolkit, FastQC, fastp, MultiQC, pigz, Python and libraries);
#   4. installs this package into that environment;
#   5. verifies every tool and runs a functional smoke test;
#   6. installs a launcher command: transcriptomics-preprocess
#
# Re-running is safe: a working environment is never modified in place. A new
# environment is built next to it and only becomes active after it passed all
# checks. Run ./install.sh --help for options.
set -Eeuo pipefail

# ---------------------------------------------------------------- constants
readonly APP="transcriptomics-preprocessor"
readonly CMD="transcriptomics-preprocess"
readonly MICROMAMBA_VERSION="2.9.0"
readonly MICROMAMBA_BUILD="0"
# SHA-256 of the conda-forge micromamba packages, taken from conda-forge's
# repodata (https://conda.anaconda.org/conda-forge/<platform>/current_repodata.json)
# on 2026-10-09. A download that does not match is never executed.
readonly MICROMAMBA_SHA256_LINUX_64="8761c382127e6363bd9e0a2451aa3ef90d071a79133f736e2f759a3bf13040dd"
readonly MICROMAMBA_SHA256_LINUX_AARCH64="e705ffeed90ce0659eb546e4b1e1028c9eaf0bc9cc854867b19ac5ce0ba5852f"
readonly CHANNEL_URL="https://conda.anaconda.org"
readonly MIN_FREE_KB=$((4 * 1024 * 1024))   # 4 GiB for environment + package cache
readonly LAUNCHER_MARK="TPP-LAUNCHER (generated by ${APP} install.sh)"
readonly ROOT_MARK=".tpp-install-root"

REPO_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
PREFIX="${XDG_DATA_HOME:-$HOME/.local/share}/${APP}"
BIN_DIR="$HOME/.local/bin"
MICROMAMBA_ARG=""
FROM_SPEC=0
REPAIR=0
SKIP_SMOKE=0
INSTALL_LAUNCHER=1
FORCE_LAUNCHER=0
STEP=0
TOTAL_STEPS=9
LOG_FILE=""
WORK_TMP=""

# ---------------------------------------------------------------- helpers
usage() {
    cat <<EOF
Usage: ./install.sh [options]

Installs ${APP} and all of its dependencies into an isolated, user-owned
environment. No administrator rights are needed and nothing outside the
installation prefix and the launcher directory is changed.

Options:
  --prefix DIR        installation directory (default: ${PREFIX})
  --bin-dir DIR       where to put the '${CMD}' launcher (default: ${BIN_DIR})
  --no-launcher       do not write a launcher into --bin-dir (one is still
                      created at <prefix>/bin/${CMD})
  --force-launcher    replace an existing '${CMD}' in --bin-dir that was not
                      created by this installer
  --micromamba PATH   use this existing micromamba executable instead of the
                      pinned private copy
  --from-spec         solve the environment from environment.yml instead of the
                      lock file (needed for platforms without a lock file)
  --repair            rebuild the environment even if a complete one exists
  --skip-smoke-test   skip the functional test (not recommended)
  -h, --help          show this help

After installation:
  ${CMD} --help         show commands
  ${CMD} doctor         check the installation
  git pull && ./install.sh             update
  ./install.sh --repair                rebuild a broken environment
  ./uninstall.sh                       remove the installation
EOF
}

say()  { printf '%s\n' "$*" | tee -a "${LOG_FILE:-/dev/null}"; }
info() { say "    $*"; }
warn() { printf 'WARNING: %s\n' "$*" | tee -a "${LOG_FILE:-/dev/null}" >&2; }
die() {
    printf '\nERROR: %s\n' "$1" | tee -a "${LOG_FILE:-/dev/null}" >&2
    [ $# -gt 1 ] && printf '  What to do: %s\n' "$2" | tee -a "${LOG_FILE:-/dev/null}" >&2
    [ -n "${LOG_FILE}" ] && printf '  Full log: %s\n' "${LOG_FILE}" >&2
    printf 'The installation is NOT complete.\n' >&2
    exit 1
}
step() { STEP=$((STEP + 1)); say ""; say "[${STEP}/${TOTAL_STEPS}] $*"; }

# shellcheck disable=SC2329  # invoked via trap
on_error() {
    local code=$? line=$1
    printf '\nERROR: unexpected failure (exit code %s) at install.sh line %s during step %s.\n' \
        "$code" "$line" "$STEP" >&2
    [ -n "${LOG_FILE}" ] && printf '  Full log: %s\n' "${LOG_FILE}" >&2
    printf 'The installation is NOT complete. Fix the problem above and re-run ./install.sh.\n' >&2
    exit "$code"
}
trap 'on_error $LINENO' ERR
# shellcheck disable=SC2329  # invoked via trap
cleanup() { [ -n "${WORK_TMP}" ] && [ -d "${WORK_TMP}" ] && rm -rf -- "${WORK_TMP}"; return 0; }
trap cleanup EXIT

have() { command -v "$1" >/dev/null 2>&1; }

download() { # url dest
    if have curl; then
        curl -fL --retry 3 --retry-delay 2 --connect-timeout 30 -sS -o "$2" "$1"
    else
        wget -q --tries=3 --timeout=30 -O "$2" "$1"
    fi
}

probe_url() { # url -> 0 if reachable
    if have curl; then
        curl -fsS -o /dev/null --max-time 30 -I "$1" 2>/dev/null || curl -fsS -o /dev/null --max-time 30 -r 0-0 "$1"
    else
        wget -q --spider --timeout=30 "$1"
    fi
}

abspath() { # make a path absolute without requiring it to exist
    case "$1" in
        /*) printf '%s\n' "$1" ;;
        *) printf '%s/%s\n' "$(pwd -P)" "$1" ;;
    esac
}

# ---------------------------------------------------------------- arguments
while [ $# -gt 0 ]; do
    case "$1" in
        --prefix) [ $# -ge 2 ] || die "--prefix needs a directory"; PREFIX="$2"; shift 2 ;;
        --bin-dir) [ $# -ge 2 ] || die "--bin-dir needs a directory"; BIN_DIR="$2"; shift 2 ;;
        --micromamba) [ $# -ge 2 ] || die "--micromamba needs a path"; MICROMAMBA_ARG="$2"; shift 2 ;;
        --no-launcher) INSTALL_LAUNCHER=0; shift ;;
        --force-launcher) FORCE_LAUNCHER=1; shift ;;
        --from-spec) FROM_SPEC=1; shift ;;
        --repair) REPAIR=1; shift ;;
        --skip-smoke-test) SKIP_SMOKE=1; shift ;;
        -h|--help) usage; exit 0 ;;
        *) usage >&2; die "unknown option: $1" ;;
    esac
done

normalise_dir() { # strip trailing slashes; reject empty values and the filesystem root
    local d="$1"
    while [ "${#d}" -gt 1 ] && [ "${d%/}" != "$d" ]; do d="${d%/}"; done
    case "$d" in ""|"/") return 1 ;; esac
    abspath "$d"
}
PREFIX="$(normalise_dir "$PREFIX")" || die "refusing to use an empty path or '/' as --prefix"
BIN_DIR="$(normalise_dir "$BIN_DIR")" || die "refusing to use an empty path or '/' as --bin-dir"
case "$PREFIX" in
    ""|"/"|"$HOME"|"/usr"|"/usr/local"|"/opt"|"/bin"|"/etc")
        die "refusing to use '$PREFIX' as installation prefix" "Choose a dedicated directory, e.g. --prefix \$HOME/.local/share/${APP}" ;;
esac
if [ -e "$PREFIX" ] && [ ! -f "$PREFIX/$ROOT_MARK" ] && [ -n "$(ls -A "$PREFIX" 2>/dev/null)" ]; then
    die "$PREFIX exists, is not empty and was not created by this installer" \
        "Choose another --prefix; the installer never writes into unrelated directories."
fi
mkdir -p "$PREFIX" || die "cannot create $PREFIX" "Check permissions or choose another --prefix."
[ -w "$PREFIX" ] || die "$PREFIX is not writable" "Choose a directory you own with --prefix."
printf 'Installation root of %s; managed by install.sh/uninstall.sh. Do not put other files here.\n' "$APP" \
    > "$PREFIX/$ROOT_MARK"
LOG_FILE="$PREFIX/install.log"
printf '\n===== install.sh started %s =====\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" >> "$LOG_FILE"

say "Transcriptomics Preprocessor installer"
say "  source:  $REPO_DIR"
say "  prefix:  $PREFIX"
say "  log:     $LOG_FILE"
[ -f "$REPO_DIR/pyproject.toml" ] && [ -f "$REPO_DIR/environment.yml" ] \
    || die "install.sh must be run from a complete copy of the repository" "Run: git clone <repository-url> && cd <repository> && ./install.sh"

# ---------------------------------------------------------------- 1. platform
step "Checking operating system and CPU architecture"
OS="$(uname -s)"
ARCH="$(uname -m)"
[ "$OS" = "Linux" ] || die "unsupported operating system: $OS" "This tool supports Linux (tested on Ubuntu 24.04, x86-64)."
case "$ARCH" in
    x86_64|amd64) PLATFORM="linux-64"; MM_SHA="$MICROMAMBA_SHA256_LINUX_64" ;;
    aarch64|arm64) PLATFORM="linux-aarch64"; MM_SHA="$MICROMAMBA_SHA256_LINUX_AARCH64" ;;
    *) die "unsupported CPU architecture: $ARCH" "Supported: x86_64 (tested) and aarch64 (untested)." ;;
esac
DISTRO="unknown Linux"
if [ -r /etc/os-release ]; then
    # shellcheck disable=SC1091
    DISTRO="$(. /etc/os-release && printf '%s %s' "${NAME:-Linux}" "${VERSION_ID:-}")"
    # shellcheck disable=SC1091
    if ! (. /etc/os-release && printf '%s %s' "${ID:-}" "${ID_LIKE:-}" | grep -qw ubuntu); then
        warn "$DISTRO is not Ubuntu. The installation will probably work but is untested."
    fi
fi
info "system: $DISTRO, $ARCH ($PLATFORM)"
[ "$PLATFORM" = "linux-aarch64" ] && warn "aarch64 is untested; the environment will be solved from environment.yml."
if [ "$(id -u)" = "0" ]; then
    warn "running as root is not needed; the installation is placed in root's home directory."
fi
LOCK_FILE="$REPO_DIR/environment-lock-${PLATFORM}.txt"
if [ "$FROM_SPEC" = 0 ] && [ ! -f "$LOCK_FILE" ]; then
    warn "no lock file for $PLATFORM; solving from environment.yml (versions may differ slightly)."
    FROM_SPEC=1
fi

# ---------------------------------------------------------------- 2. utilities
step "Checking basic utilities and free disk space"
missing=()
for tool in tar bzip2 sha256sum mktemp df uname grep sed; do have "$tool" || missing+=("$tool"); done
have curl || have wget || missing+=("curl (or wget)")
if [ ${#missing[@]} -gt 0 ]; then
    die "missing basic system utilities: ${missing[*]}" \
        "Ask an administrator to install them, e.g. on Ubuntu: sudo apt install curl tar bzip2 coreutils. (This installer never runs sudo itself.)"
fi
info "utilities: ok ($(have curl && echo curl || echo wget), tar, bzip2, sha256sum)"
free_kb="$(df -Pk "$PREFIX" | awk 'NR==2 {print $4}')"
info "free space at $PREFIX: $((free_kb / 1024)) MiB"
[ "$free_kb" -ge "$MIN_FREE_KB" ] || die "not enough free space at $PREFIX ($((free_kb / 1024)) MiB; need about $((MIN_FREE_KB / 1024)) MiB)" \
    "Free some space or use --prefix on a larger disk."
WORK_TMP="$(mktemp -d "${PREFIX}/.install-tmp.XXXXXX")"

# ---------------------------------------------------------------- 3. micromamba
step "Locating micromamba (environment manager)"
need_network=0
MM=""
if [ -n "$MICROMAMBA_ARG" ]; then
    MM="$(abspath "$MICROMAMBA_ARG")"
    [ -x "$MM" ] || die "--micromamba $MM is not an executable file"
    info "using the micromamba given with --micromamba: $MM ($("$MM" --version 2>/dev/null || echo 'version unknown'))"
elif [ -x "$PREFIX/bin/micromamba" ] && [ "$("$PREFIX/bin/micromamba" --version 2>/dev/null || true)" = "$MICROMAMBA_VERSION" ]; then
    MM="$PREFIX/bin/micromamba"
    info "found the private micromamba $MICROMAMBA_VERSION from a previous installation"
else
    need_network=1
fi

check_network() {
    info "checking access to $CHANNEL_URL ..."
    if ! probe_url "$CHANNEL_URL/conda-forge/noarch/repodata.json"; then
        die "cannot reach $CHANNEL_URL (conda-forge / bioconda package channels)" \
            "Connect to the internet (or configure your proxy via HTTPS_PROXY) and re-run ./install.sh. Required downloads: micromamba ${MICROMAMBA_VERSION} from conda-forge and the packages listed in $(basename "$LOCK_FILE") (SRA Toolkit, FastQC, fastp, MultiQC, pigz, Python)."
    fi
    info "package channels reachable"
}

if [ "$need_network" = 1 ]; then
    check_network
    pkg="micromamba-${MICROMAMBA_VERSION}-${MICROMAMBA_BUILD}.tar.bz2"
    url="$CHANNEL_URL/conda-forge/$PLATFORM/$pkg"
    info "downloading $url"
    download "$url" "$WORK_TMP/$pkg" || die "download of micromamba failed" "Check the network and re-run."
    actual="$(sha256sum "$WORK_TMP/$pkg" | awk '{print $1}')"
    if [ "$actual" != "$MM_SHA" ]; then
        die "checksum mismatch for $pkg (expected $MM_SHA, got $actual); the file was NOT used" \
            "The download may be corrupted or tampered with. Re-run later; report the problem if it persists."
    fi
    info "SHA-256 verified: $actual"
    tar -xjf "$WORK_TMP/$pkg" -C "$WORK_TMP" bin/micromamba
    mkdir -p "$PREFIX/bin"
    install -m 0755 "$WORK_TMP/bin/micromamba" "$PREFIX/bin/micromamba.new"
    mv -f "$PREFIX/bin/micromamba.new" "$PREFIX/bin/micromamba"
    MM="$PREFIX/bin/micromamba"
    [ "$("$MM" --version)" = "$MICROMAMBA_VERSION" ] || die "the downloaded micromamba does not run correctly"
    info "installed micromamba $MICROMAMBA_VERSION to $MM"
fi
export MAMBA_ROOT_PREFIX="$PREFIX/mamba-root"   # private package cache; ~/.condarc etc. are ignored (--no-rc)

# ---------------------------------------------------------------- 4. environment
step "Creating the isolated software environment"
if [ "$FROM_SPEC" = 1 ]; then SPEC="$REPO_DIR/environment.yml"; else SPEC="$LOCK_FILE"; fi
SPEC_HASH="$( { cat "$SPEC"; printf '%s' "$PLATFORM"; } | sha256sum | cut -c1-12)"
ENV_DIR="$PREFIX/envs/tpp-$SPEC_HASH"
info "specification: $(basename "$SPEC") (id $SPEC_HASH)"
mkdir -p "$PREFIX/envs"
if [ -f "$ENV_DIR/.tpp-env-complete" ] && [ "$REPAIR" = 0 ]; then
    info "a complete environment for this specification already exists: $ENV_DIR (it will be re-verified)"
else
    if [ -e "$ENV_DIR" ]; then
        [ -f "$ENV_DIR.managed" ] || die "$ENV_DIR exists but is not managed by this installer" "Remove it manually if it is not needed."
        info "removing incomplete or to-be-repaired environment $ENV_DIR"
        rm -rf -- "$ENV_DIR"
    fi
    [ "$need_network" = 1 ] || check_network
    printf 'created by install.sh %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" > "$ENV_DIR.managed"
    info "installing packages (this downloads roughly 0.5-1 GB the first time; it can take several minutes)"
    if [ "$FROM_SPEC" = 1 ]; then
        "$MM" create -y --no-rc -p "$ENV_DIR" -f "$SPEC" --override-channels -c conda-forge -c bioconda \
            --strict-channel-priority >> "$LOG_FILE" 2>&1 \
            || die "creating the environment from environment.yml failed" "See the log; network problems are the most common cause. Re-run ./install.sh."
    else
        "$MM" create -y --no-rc -p "$ENV_DIR" -f "$SPEC" >> "$LOG_FILE" 2>&1 \
            || die "creating the environment from the lock file failed" "See the log; network problems are the most common cause. Re-run ./install.sh (or try --from-spec)."
    fi
    info "environment created: $ENV_DIR"
fi

# ---------------------------------------------------------------- 5. package
step "Installing the transcriptomics-preprocessor package into the environment"
# --no-deps/--no-index: every dependency comes from the conda environment; pip never contacts PyPI.
PIP_CONFIG_FILE=/dev/null PYTHONNOUSERSITE=1 PIP_DISABLE_PIP_VERSION_CHECK=1 \
    "$ENV_DIR/bin/python" -m pip install --no-deps --no-build-isolation --no-index --force-reinstall \
    --root-user-action=ignore "$REPO_DIR" >> "$LOG_FILE" 2>&1 \
    || die "installing the Python package failed" "See the log. Re-run ./install.sh --repair."
info "installed $("$ENV_DIR/bin/python" -c 'import transcriptomics_preprocessor as t; print(t.__version__)') into $ENV_DIR"

# ---------------------------------------------------------------- 6. verification
step "Verifying executables and versions"
run_in_env() { (eval "$("$MM" shell activate -s bash -p "$ENV_DIR")" && unset PYTHONPATH && "$@"); }
if ! run_in_env "$CMD" doctor >> "$LOG_FILE" 2>&1; then
    run_in_env "$CMD" doctor || true
    die "the dependency check failed (see above)" "Re-run ./install.sh --repair; if it fails again, report the log."
fi
run_in_env "$CMD" doctor --json > "$WORK_TMP/doctor.json" 2>>"$LOG_FILE"
"$ENV_DIR/bin/python" - "$WORK_TMP/doctor.json" <<'PY' | tee -a "$LOG_FILE"
import json, sys
d = json.load(open(sys.argv[1]))
for key, t in d["tools"].items():
    note = "" if t["version_matches_pin"] else f"  (tested: {t['expected']})"
    print(f"    {key:13s} {t['version']}{note}")
PY

# ---------------------------------------------------------------- 7. smoke test
step "Running a functional smoke test"
if [ "$SKIP_SMOKE" = 1 ]; then
    warn "smoke test skipped (--skip-smoke-test); the tools were not exercised on data"
else
    if ! run_in_env "$CMD" doctor --smoke-test >> "$LOG_FILE" 2>&1; then
        run_in_env "$CMD" doctor --smoke-test | grep -E "smoke|FAIL" || true
        die "the smoke test failed: the tools are installed but did not process test data correctly" \
            "See the log. Re-run ./install.sh --repair."
    fi
    info "FastQC, fastp and MultiQC processed a synthetic dataset correctly; SRA Toolkit executables run"
fi

# ---------------------------------------------------------------- 8. activate
step "Activating the new environment and writing the launcher"
touch "$ENV_DIR/.tpp-env-complete"
ln -sfn "envs/tpp-$SPEC_HASH" "$PREFIX/env.new"
mv -Tf "$PREFIX/env.new" "$PREFIX/env"
info "active environment: $PREFIX/env -> envs/tpp-$SPEC_HASH"

write_launcher() { # dest
    local q_prefix q_mm
    q_prefix="$(printf '%q' "$PREFIX")"
    q_mm="$(printf '%q' "$MM")"
    cat > "$1.new" <<EOF
#!/usr/bin/env bash
# ${LAUNCHER_MARK}
# Runs ${CMD} inside its private environment. Re-create with ./install.sh.
set -e
PREFIX=${q_prefix}
MM=${q_mm}
ENV_DIR="\$PREFIX/env"
if [ ! -x "\$ENV_DIR/bin/${CMD}" ] || [ ! -x "\$MM" ]; then
    echo "ERROR: the ${APP} installation in \$PREFIX is incomplete or was removed." >&2
    echo "  What to do: run ./install.sh (or ./install.sh --repair) from the repository." >&2
    exit 3
fi
export MAMBA_ROOT_PREFIX="\$PREFIX/mamba-root"
unset PYTHONPATH PYTHONHOME
eval "\$("\$MM" shell activate -s bash -p "\$ENV_DIR")"
exec "\$ENV_DIR/bin/${CMD}" "\$@"
EOF
    chmod 0755 "$1.new"
    mv -f "$1.new" "$1"
}
mkdir -p "$PREFIX/bin"
write_launcher "$PREFIX/bin/$CMD"
info "launcher: $PREFIX/bin/$CMD"
LAUNCHER="$PREFIX/bin/$CMD"
if [ "$INSTALL_LAUNCHER" = 1 ]; then
    mkdir -p "$BIN_DIR"
    target="$BIN_DIR/$CMD"
    if [ -e "$target" ] && ! grep -q "TPP-LAUNCHER" "$target" 2>/dev/null && [ "$FORCE_LAUNCHER" = 0 ]; then
        warn "$target exists and was not created by this installer; it was left unchanged."
        warn "Use $PREFIX/bin/$CMD, or re-run with --force-launcher to replace it."
    else
        write_launcher "$target"
        LAUNCHER="$target"
        info "launcher: $target"
    fi
fi
# Verify the launcher itself, from a clean environment, exactly as a user would call it.
env -i HOME="$HOME" PATH="/usr/bin:/bin" LANG="${LANG:-C.UTF-8}" "$LAUNCHER" --version >> "$LOG_FILE" 2>&1 \
    || die "the launcher $LAUNCHER does not work" "See the log; re-run ./install.sh --repair."
info "launcher works: $("$LAUNCHER" --version)"

# ---------------------------------------------------------------- 9. summary
step "Summary"
{
    printf 'version: %s\n' "$("$ENV_DIR/bin/python" -c 'import transcriptomics_preprocessor as t; print(t.__version__)')"
    printf 'installed: %s\nsource: %s\nenvironment: %s\nspecification: %s\nlauncher: %s\nmicromamba: %s\n' \
        "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$REPO_DIR" "$ENV_DIR" "$SPEC" "$LAUNCHER" "$MM"
} > "$PREFIX/install-info.txt"
old_envs="$(find "$PREFIX/envs" -mindepth 1 -maxdepth 1 -type d -name 'tpp-*' ! -name "tpp-$SPEC_HASH" | wc -l)"
say "Installation complete."
say ""
say "  Run:        $CMD --help"
say "  Check:      $CMD doctor"
say "  Update:     git pull && ./install.sh"
say "  Repair:     ./install.sh --repair"
say "  Uninstall:  ./uninstall.sh"
[ "$old_envs" -gt 0 ] && say "  Note: $old_envs older environment(s) kept in $PREFIX/envs; remove with ./uninstall.sh --prune-old-envs"
case ":$PATH:" in
    *":$BIN_DIR:"*) ;;
    *)
        if [ "$LAUNCHER" = "$BIN_DIR/$CMD" ]; then
            say ""
            say "  NOTE: $BIN_DIR is not on your PATH in this shell, so '$CMD' is not found yet."
            say "  On Ubuntu it is added automatically at your next login (via ~/.profile)."
            say "  For this terminal, run:   export PATH=\"$BIN_DIR:\$PATH\""
            say "  Or call the launcher directly: $LAUNCHER"
        fi
        ;;
esac
exit 0
