"""MultiQC aggregation (raw QC and post-cleaning QC are separate reports)."""

from __future__ import annotations

from pathlib import Path

from . import __version__
from .errors import IntegrityError
from .runner import run_command
from .utils import atomic_write_text, remove_if_exists, safe_rmtree


def build_command(file_list: Path, outdir: Path, filename: str, title: str) -> list[str]:
    return [
        "multiqc",
        "--file-list",
        str(file_list),
        "--outdir",
        str(outdir),
        "--filename",
        filename,
        "--title",
        title,
        "--comment",
        f"Generated by transcriptomics-preprocess {__version__}",
        "--force",
        "--no-ansi",
        # Privacy/offline: no version check, no AI features, no MegaQC upload.
        "--no-version-check",
        "--no-ai",
        "--no-megaqc-upload",
    ]


def run(
    inputs: list[Path],
    outdir: Path,
    filename: str,
    title: str,
    log: Path,
    timeout_s: float,
    root: Path,
) -> dict[str, Path]:
    """Run MultiQC on an explicit list of report files.

    Passing an explicit file list (instead of scanning directories) guarantees
    that reports from samples not in the current run are never included.
    """
    if not inputs:
        raise IntegrityError("no QC reports available to aggregate")
    outdir.mkdir(parents=True, exist_ok=True)
    html = outdir / f"{filename}.html"
    data_dir = outdir / f"{filename}_data"
    remove_if_exists(html)
    if data_dir.exists():
        safe_rmtree(data_dir, root)
    file_list = outdir / f"{filename}_inputs.txt"
    atomic_write_text(file_list, "".join(f"{p}\n" for p in inputs))
    run_command(
        build_command(file_list, outdir, filename, title),
        log_path=log,
        timeout=timeout_s,
        description=f"MultiQC {filename}",
    )
    if not html.is_file() or html.stat().st_size == 0:
        raise IntegrityError(
            f"MultiQC finished but {html.name} is missing or empty", hint=f"See {log}"
        )
    outputs = {"html": html, "inputs": file_list}
    general = data_dir / "multiqc_general_stats.txt"
    if general.is_file():
        outputs["general_stats"] = general
    return outputs
